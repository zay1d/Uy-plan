def side(sign):
    rooms, unit, riser, shafts, ducts, boxes, holes, grilles, elec, wires = left_side()
    tag = "Л" if sign == "L" else "П"
    if sign == "R":
        ax = lambda x: WING_AXIS if x < PART_X else CENTER_AXIS
        mp_ = lambda p: mirror_x(p, ax(p[0]))
        mr = lambda r: mirror_rect(r, ax((r[0] + r[1]) / 2))
        unit = dict(unit, rect=mr(unit["rect"]))
        riser = dict(riser, rect=mr(riser["rect"]))
        shafts = [dict(s, rect=mr(s["rect"])) for s in shafts]
        ducts = [dict(d, pts=[mp_(p) for p in d["pts"]]) for d in ducts]
        boxes = [dict(b, pts=[mp_(p) for p in b["pts"]]) for b in boxes]
        holes = [dict(h, pos=mp_(h["pos"])) for h in holes]
        grilles = [dict(g, pos=mp_(g["pos"]), n=[-g["n"][0], g["n"][1]]) for g in grilles]
        elec = [dict(e, pos=mp_(e["pos"]), nrm=[-e["nrm"][0], e["nrm"][1]] if e.get("nrm") else None) for e in elec]
        wires = [dict(wi, pts=[mp_(p) for p in wi["pts"]]) for wi in wires]
    for s in shafts:
        s["name"] = (f"Узел {s['id']}-{tag}" if s["kind"] == "node" else f"Гильза {s['id']}-{tag}")
    unit["name"] = f"Рекуператор {tag}"
    total = sum(r["flow"] for r in rooms.values() if not r["reserve"])
    reserve = sum(r["flow"] for r in rooms.values() if r["reserve"])
    for d in ducts:
        q = flow_of_duct(d, rooms)
        d["flow"] = q
        d["v"] = round(q / 3600 / (math.pi * (d["d"] / 2000) ** 2), 1) if q else None
    for g in grilles:
        g["flow"] = rooms[g["room"]]["flow"]
    return {"side": sign, "tag": tag, "rooms": list(rooms.values()), "unit": unit, "riser": riser, "shafts": shafts,
            "ducts": ducts, "boxes": boxes, "holes": holes, "grilles": grilles, "elec": elec, "wires": wires,
            "total": total, "totalWithReserve": total + reserve}


def flow_of_duct(d, rooms):
    if "room" in d:
        return rooms[d["room"]]["flow"]
    if d["type"] in ("oda", "eha") or d.get("to") == "main":
        return sum(r["flow"] for r in rooms.values() if not r["reserve"])
    if d.get("to") == "А":
        return rooms["R"]["flow"] + rooms["D1"]["flow"]
    return 0


